CREATE TABLE dbo.APP_USER (
    UserId      INT IDENTITY(1,1) NOT NULL,
    Name        NVARCHAR(100) NOT NULL,
    IsActive    BIT NOT NULL CONSTRAINT DF_APP_USER_IsActive DEFAULT (1),

    CONSTRAINT PK_APP_USER PRIMARY KEY CLUSTERED (UserId)
);

ALTER TABLE dbo.FAULT_HISTORY WITH CHECK
    ADD CONSTRAINT FK_FAULT_HISTORY_APP_USER
    FOREIGN KEY (ChangedByUserId) REFERENCES dbo.APP_USER (UserId);
