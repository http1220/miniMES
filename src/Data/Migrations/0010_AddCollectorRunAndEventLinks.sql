CREATE TABLE dbo.COLLECTOR_RUN (
    RunId UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_COLLECTOR_RUN PRIMARY KEY,
    StartedAtUtc DATETIME2(3) NOT NULL
);

ALTER TABLE dbo.SAMPLE WITH CHECK ADD CONSTRAINT FK_SAMPLE_COLLECTOR_RUN
    FOREIGN KEY (RunId) REFERENCES dbo.COLLECTOR_RUN (RunId);
ALTER TABLE dbo.ALARM_EVENT WITH CHECK ADD CONSTRAINT FK_ALARM_EVENT_COLLECTOR_RUN
    FOREIGN KEY (RunId) REFERENCES dbo.COLLECTOR_RUN (RunId);
ALTER TABLE dbo.SAMPLE WITH CHECK ADD CONSTRAINT FK_SAMPLE_EQUIPMENT
    FOREIGN KEY (EquipmentId) REFERENCES dbo.EQUIPMENT (EquipmentId);
ALTER TABLE dbo.ALARM WITH CHECK ADD CONSTRAINT FK_ALARM_EQUIPMENT
    FOREIGN KEY (EquipmentId) REFERENCES dbo.EQUIPMENT (EquipmentId);

ALTER TABLE dbo.ALARM_EVENT DROP CONSTRAINT CK_ALARM_EVENT_EventType;
-- 1 = 발생, 2 = 해제, 3 = 현재 상태 보고(이상), 4 = 현재 상태 보고(정상)
ALTER TABLE dbo.ALARM_EVENT WITH CHECK ADD CONSTRAINT CK_ALARM_EVENT_EventType
    CHECK (EventType IN (1, 2, 3, 4));

ALTER TABLE dbo.ALARM_EVENT ADD AlarmId INT NULL;
-- 새 열을 추가한 뒤 별도 배치로 FK를 컴파일한다.
EXEC(N'ALTER TABLE dbo.ALARM_EVENT WITH CHECK ADD CONSTRAINT FK_ALARM_EVENT_ALARM
    FOREIGN KEY (AlarmId) REFERENCES dbo.ALARM (AlarmId)');

DECLARE @constraintName sysname;
SELECT @constraintName = d.name
FROM sys.default_constraints d
JOIN sys.columns c ON c.object_id = d.parent_object_id AND c.column_id = d.parent_column_id
WHERE d.parent_object_id = OBJECT_ID('dbo.SAMPLE') AND c.name = 'RecordedAtUtc';
IF @constraintName IS NOT NULL
BEGIN
    DECLARE @dropSql nvarchar(max) = N'ALTER TABLE dbo.SAMPLE DROP CONSTRAINT ' + QUOTENAME(@constraintName);
    EXEC(@dropSql);
END;
